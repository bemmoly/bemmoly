// Copies the Lucide icons the film uses into src/icons.js, so the page has no runtime dependency.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const NAMES = `square-kanban file-text sparkles contact-round timer receipt laptop key-round user-round-plus
shield-check target life-buoy git-branch house inbox circle-user search plus chevron-down chevron-right
panel-left layout-grid list-checks calendar-days check check-check folder-kanban chart-column wallet plane
credit-card boxes wrench users network palmtree folder-lock briefcase globe scroll-text messages-square
book-open shapes bell settings filter arrow-up-down arrow-right zap webhook github gitlab terminal
lock database server hard-drive refresh-cw rotate-ccw shield cloud-off eye-off upload download link
message-square at-sign hash star copy circle-check badge-check infinity dollar-sign heart rocket
git-pull-request git-merge play circle-dot cpu box layers sun moon palette blocks puzzle plug
send bot wand-sparkles quote type bold italic list image map calendar-check file-signature
gauge activity flag milestone clock triangle-alert kanban list-todo ellipsis gift`.split(/\s+/).filter(Boolean);

const out = {};
for (const n of NAMES) {
  const p = `node_modules/lucide-static/icons/${n}.svg`;
  if (!existsSync(p)) { console.warn('missing icon', n); continue; }
  const svg = readFileSync(p, 'utf8');
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
}
writeFileSync('src/icons.js', '// Generated by tools/icons.mjs from lucide-static 1.47.0 (ISC). Do not edit.\nexport const ICONS = ' + JSON.stringify(out, null, 0) + ';\n');
console.log(Object.keys(out).length, 'icons');
